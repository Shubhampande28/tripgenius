type QuickIndianCity = {
  slug: string;
  name: string;
  state: string;
  tagline: string;
  description: string;
  bestTime: string;
  budget: string;
  language: string;
  vibes: string[];
  gradient: string;
  accentColor: string;
  image: string;
  areaTagline: string;
  highlights: string[];
};

function quickIndianCity(city: QuickIndianCity): City {
  return {
    slug: city.slug,
    name: city.name,
    state: city.state,
    country: 'India',
    flag: '🇮🇳',
    tagline: city.tagline,
    description: city.description,
    heroDescription: city.description,
    stats: {
      bestTime: city.bestTime,
      budget: city.budget,
      language: city.language,
      currency: 'INR (Rupee)',
    },
    vibes: city.vibes,
    gradient: city.gradient,
    accentColor: city.accentColor,
    image: '',
    heroImage: '',
    areas: [
      {
        name: 'Essential Stops',
        emoji: '📍',
        accentColor: city.accentColor,
        image: '',
        tagline: city.areaTagline,
        spots: city.highlights.map((name) => ({ name, tag: 'Highlight' })),
      },
    ],
  };
}

